    public static Material getMaterial(String name) {
        if (name == null) return null;
        try {
            return valueOf(name.trim().toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException ignored) {
            return null;
        }
    }

    public static Material matchMaterial(String name) {
        return getMaterial(name);
    }

    /** Current registry name for compatibility constants retained by older abilities/configs. */
    public Material canonical() {
        return switch (this) {
            case BLOCK_RAW_GOLD -> RAW_GOLD_BLOCK;
            case CHAIN -> IRON_CHAIN;
            case GRASS -> SHORT_GRASS;
            case GRASS_PATH -> DIRT_PATH;
            default -> this;
        };
    }

    public BlockData createBlockData() {
        if (this == FIRE || this == SOUL_FIRE) return new Fire(this);
        if (this == SNOW) return new com.projectkorra.projectkorra.platform.mc.block.data.type.Snow();
        if (this == GRASS_BLOCK || this == MYCELIUM || this == PODZOL) return new Snowable(this);
        return (this == WATER || this == LAVA || this == LIGHT || name().contains("CAULDRON")) ? new Levelled(this) : new BlockData(this);
    }

    public BlockData createBlockData(Consumer<BlockData> consumer) {
        BlockData data = createBlockData();
        consumer.accept(data);
        return data;
    }

